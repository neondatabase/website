// Generates src/constants/docs-last-modified.js: a fallback map of
// slug -> last-modified ISO date for docs pages that have NO `updatedOn`
// frontmatter field. The value is the file's last git commit date.
//
// Why this is committed rather than computed at build time: Vercel builds use a
// shallow git clone, so per-file `git log` history is not reliably available
// during the build. We generate this map locally (where full history exists) and
// commit it. Pages that DO have an `updatedOn` frontmatter field keep using that
// value (it is auto-stamped on commit); this map only covers the pages missing it.
//
// Regenerate with: npm run generate:docs-last-modified

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const { glob } = require('glob');

const DOCS_DIR = 'content/docs';
const OUTPUT_FILE = path.join(process.cwd(), 'src/constants/docs-last-modified.js');

const files = glob
  .sync(`${DOCS_DIR}/**/*.md`, {
    ignore: ['**/README.md', '**/unused/**', '**/shared-content/**', '**/GUIDE_TEMPLATE.md'],
  })
  .sort();

const map = {};

for (const file of files) {
  const content = fs.readFileSync(file, 'utf-8');
  const fmEnd = content.indexOf('\n---', 3);
  const frontmatter = fmEnd === -1 ? '' : content.slice(0, fmEnd);

  // Pages with their own updatedOn already have an accurate, auto-stamped date.
  if (/^updatedOn:/m.test(frontmatter)) continue;

  let iso = '';
  try {
    iso = execSync(`git log -1 --format=%cI -- "${file}"`, { encoding: 'utf-8' }).trim();
  } catch {
    iso = '';
  }
  if (!iso) continue;

  const slug = file.replace(`${DOCS_DIR}/`, '').replace(/\.md$/, '');
  map[slug] = iso;
}

const body = `// GENERATED by src/scripts/generate-docs-last-modified.js - do not edit by hand.
// Fallback last-modified dates (the file's last git commit) for docs pages that
// have no \`updatedOn\` frontmatter field. Pages with \`updatedOn\` use that value.
// Regenerate with: npm run generate:docs-last-modified

const DOCS_LAST_MODIFIED = ${JSON.stringify(map, null, 2)};

export default DOCS_LAST_MODIFIED;
`;

fs.writeFileSync(OUTPUT_FILE, body);

console.log(
  `Wrote ${Object.keys(map).length} docs last-modified dates to ${path.relative(
    process.cwd(),
    OUTPUT_FILE
  )}`
);
